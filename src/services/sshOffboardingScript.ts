/**
 * src/services/sshOffboardingScript.ts
 *
 * The OFFBOARDING scripts: the inverse of the SSH onboarding scripts in
 * sshOnboardingScript.ts (business rule 166).
 *
 * Onboarding leaves four things on every host it runs on — an authorized key,
 * (in "create" mode) a local account, on Linux a passwordless-sudo drop-in,
 * and a firewall rule — and until this file existed Polaris could generate
 * all of them and remove none. A host that left the fleet, or a fleet that
 * stopped using Polaris, kept a standing administrative SSH path with no
 * supported way to close it.
 *
 * Each script removes ONLY what the onboarding script provably put there, and
 * says what it left and why:
 *
 *   - Keys: the current deployment key and every retired one, matched on the
 *     key body. Every other line in the file is kept.
 *   - Account: removed only in "create" mode AND only when it still carries
 *     the marker the onboarding script stamped on it (the Windows Description,
 *     the Linux GECOS comment). An account that existed before, or was
 *     repurposed since, is left alone.
 *   - Sudoers drop-in (Linux): removed only when it carries the "Managed by
 *     Polaris" header.
 *   - Firewall: the Polaris rule is removed. On Windows the built-in OpenSSH
 *     rule that onboarding disabled is NOT re-enabled — closed is the safe
 *     state, and the script prints the one command that restores it.
 *
 * Never touched: the OpenSSH server itself, and the Polaris Agent (uninstall
 * that from Polaris first — the script warns when it is still installed,
 * because after it runs Polaris can no longer reach the host to do so).
 *
 * Same input contract as the onboarding builders: validated values only,
 * emitted as single-quoted literals, AppError on anything else.
 */

import { AppError } from "../utils/errors.js";
import {
  assertValidLinuxUsername,
  assertValidPublicKey,
  assertValidRetiredKeys,
  assertValidServerIp,
  assertValidUsername,
  FIREWALL_RULE_NAME,
  LINUX_SUDOERS_PATH,
  OPENSSH_BUILTIN_RULE_NAME,
  POLARIS_PS_HELPERS,
  POLARIS_PS_STRIP_HELPER,
  POLARIS_SH_HELPERS,
  POLARIS_SH_STRIP_HELPER,
  psLiteral,
  shLiteral,
  SID_ADMINISTRATORS,
  WINDOWS_ACCOUNT_DESCRIPTION,
  type SshOnboardingAccountMode,
} from "./sshOnboardingScript.js";

export interface OffboardingScriptOptions {
  /** The current deployment key. */
  publicKey: string;
  /** Keys rotated away from; removed along with the current one. */
  retiredPublicKeys?: string[];
  username: string;
  accountMode: SshOnboardingAccountMode;
  /** When set, the firewall allowance for this address is removed too. */
  polarisServerIp?: string;
}

/** The GECOS comment the Linux onboarding script creates its account with. */
export const LINUX_ACCOUNT_COMMENT = "Polaris Agent deployment";

function assertAccountMode(mode: unknown): asserts mode is SshOnboardingAccountMode {
  if (mode !== "create" && mode !== "existing") {
    throw new AppError(400, 'Account mode must be "create" or "existing"');
  }
}

// ─── Windows ──────────────────────────────────────────────────────────────

const WINDOWS_OFFBOARDING_PS = `
# ---------------------------------------------------------------------------
# Polaris — Windows SSH OFFBOARDING
#
# Removes what the Polaris SSH onboarding script put on this machine:
#   1. the Polaris public key(s) from administrators_authorized_keys
#   2. __ACCOUNT_SUMMARY__
#   3. the Polaris inbound firewall rule for TCP/22
#
# It does NOT:
#   - uninstall or stop the OpenSSH Server (other people may rely on it)
#   - re-enable Windows' own OpenSSH firewall rule, which onboarding disabled
#     (port 22 stays closed; the command to restore it is printed at the end)
#   - uninstall the Polaris Agent. Uninstall the agent FROM POLARIS FIRST:
#     once this script has run, Polaris can no longer sign in to do it.
#
# Generated by Polaris. Contains no machine-specific values, so the same file
# runs unchanged on every endpoint.
#
# HOW TO RUN IT
#   Intune  : Devices > Scripts (run once). Run as SYSTEM, 64-bit host = Yes.
#             Unassign the onboarding Remediation first, or it will put
#             everything back on its next cycle.
#   GPO/SCCM/Arc/RMM : any run-as-SYSTEM script job.
#   Ad hoc  : Invoke-Command -ComputerName ... -FilePath <this file>
#
# Idempotent: safe to run again. Exits 0 when everything it owns is gone,
# 1 when something could not be removed.
#
# REVIEW BEFORE DEPLOYING. This removes Polaris's administrative access.
# ---------------------------------------------------------------------------

$ErrorActionPreference = 'Stop'

$PolarisKeys = @(__KEYS__)
$PolarisUser = __USERNAME__
$failed = $false

__PS_HELPERS__

__PS_STRIP_HELPER__

# --- 1. Remove the Polaris key(s) ---------------------------------------------
# Only lines whose key matches are removed. Every other key in this file
# belongs to someone else and is kept; the file's ACL is not changed.
try {
  $authKeys = Get-PolarisAuthorizedKeysPath
  if (Test-Path -LiteralPath $authKeys) {
    $removed = Remove-PolarisKeys -Path $authKeys -Keys $PolarisKeys
    Write-Host ('Removed ' + $removed + ' Polaris key line(s) from ' + $authKeys)
  } else {
    Write-Host 'No administrators_authorized_keys file - no key to remove'
  }
} catch {
  Write-Host ('error: could not remove the Polaris key - ' + $_.Exception.Message)
  $failed = $true
}

__ACCOUNT_BLOCK__

# --- 3. Firewall --------------------------------------------------------------
try {
  $fwName = __FW_NAME__
  $polarisRules = @(Get-NetFirewallRule -DisplayName $fwName -ErrorAction SilentlyContinue)
  if ($polarisRules.Count -gt 0) {
    $polarisRules | Remove-NetFirewallRule
    Write-Host ('Removed firewall rule "' + $fwName + '"')
  } else {
    Write-Host ('No firewall rule "' + $fwName + '" present')
  }
  $builtInRules = @(Get-NetFirewallRule -Name __BUILTIN_FW_NAME__ -ErrorAction SilentlyContinue)
  foreach ($rule in $builtInRules) {
    if ($rule.Enabled -ne 'True') {
      Write-Host ('note: built-in rule ' + $rule.Name + ' is disabled and was left that way, so inbound TCP/22 is closed.')
      Write-Host ('      To restore the Windows default:  Enable-NetFirewallRule -Name ' + $rule.Name)
    }
  }
} catch {
  Write-Host ('error: could not update the firewall - ' + $_.Exception.Message)
  $failed = $true
}

# --- 4. What was left ----------------------------------------------------------
if (Get-Service -Name 'polaris-agent' -ErrorAction SilentlyContinue) {
  Write-Host 'warning: the Polaris Agent service is still installed on this machine. This script does not remove it.'
}
Write-Host 'OpenSSH Server was not changed.'

if ($failed) {
  Write-Host 'Polaris SSH offboarding finished WITH ERRORS'
  exit 1
}
Write-Host 'Polaris SSH offboarding complete'
exit 0
`.trim();

/** accountMode="create": the account is ours only while it still carries our description. */
const OFFBOARD_ACCOUNT_CREATE_PS = `
# --- 2. Local account ----------------------------------------------------------
# Removed only when it is the account the onboarding script created: that
# script stamps a fixed description on it. An account with any other
# description existed before onboarding, or has been repurposed, and is kept.
try {
  $polarisAccount = Get-LocalUser -Name $PolarisUser -ErrorAction SilentlyContinue
  if (-not $polarisAccount) {
    Write-Host ('Local account ' + $PolarisUser + ' not present')
  } elseif ($polarisAccount.Description -ne __ACCOUNT_DESCRIPTION__) {
    Write-Host ('Left local account ' + $PolarisUser + ' alone: it does not carry the Polaris onboarding description, so this script did not create it')
  } else {
    Remove-LocalUser -Name $PolarisUser
    Write-Host ('Removed local account ' + $PolarisUser + ' (its profile folder, if one exists, was not deleted)')
  }
} catch {
  Write-Host ('error: could not remove local account ' + $PolarisUser + ' - ' + $_.Exception.Message)
  $failed = $true
}
`.trim();

/** accountMode="existing": never ours to remove. */
const OFFBOARD_ACCOUNT_EXISTING_PS = `
# --- 2. Account -----------------------------------------------------------------
# Onboarding used an account that already existed. It is not removed, disabled
# or taken out of any group here.
Write-Host ('Left account ' + $PolarisUser + ' alone (onboarding did not create it)')
`.trim();

export function buildWindowsOffboardingScript(opts: OffboardingScriptOptions): string {
  const publicKey = assertValidPublicKey(opts.publicKey);
  assertAccountMode(opts.accountMode);
  const username = assertValidUsername(opts.username, opts.accountMode);
  const keys = [publicKey, ...assertValidRetiredKeys(opts.retiredPublicKeys, publicKey)];

  const accountBlock =
    opts.accountMode === "create"
      ? OFFBOARD_ACCOUNT_CREATE_PS.replace(/__ACCOUNT_DESCRIPTION__/g, () => psLiteral(WINDOWS_ACCOUNT_DESCRIPTION))
      : OFFBOARD_ACCOUNT_EXISTING_PS;

  return WINDOWS_OFFBOARDING_PS
    .replace(/__USERNAME__/g, () => psLiteral(username))
    .replace(/__PS_HELPERS__/g, () => POLARIS_PS_HELPERS)
    .replace(/__PS_STRIP_HELPER__/g, () => POLARIS_PS_STRIP_HELPER)
    .replace(/__ACCOUNT_BLOCK__/g, () => accountBlock)
    .replace(/__FW_NAME__/g, () => psLiteral(FIREWALL_RULE_NAME))
    .replace(/__BUILTIN_FW_NAME__/g, () => psLiteral(OPENSSH_BUILTIN_RULE_NAME))
    .replace(/__SID_ADMINS__/g, () => psLiteral(SID_ADMINISTRATORS))
    .replace(
      /__ACCOUNT_SUMMARY__/g,
      () => opts.accountMode === "create"
        ? `the local account '${username}', if the onboarding script created it`
        : `nothing for the account '${username}' - onboarding did not create it, so it is left alone`,
    )
    // Last: key text is the one operator-influenced value with free characters.
    .replace(/__KEYS__/g, () => keys.map(psLiteral).join(", "));
}

// ─── Linux ────────────────────────────────────────────────────────────────

const LINUX_OFFBOARDING_SH = `#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# Polaris — Linux SSH OFFBOARDING
#
# Removes what the Polaris SSH onboarding script put on this machine:
#   1. the Polaris public key(s) from the account's authorized_keys
#   2. the passwordless-sudo drop-in __SUDOERS_PATH__
#   3. __ACCOUNT_SUMMARY__
#   4. __FIREWALL_SUMMARY__
#
# It does NOT:
#   - stop, disable or uninstall sshd
#   - uninstall the Polaris Agent. Uninstall the agent FROM POLARIS FIRST:
#     once this script has run, Polaris can no longer sign in to do it.
#
# Generated by Polaris. Contains no machine-specific values, so the same file
# runs unchanged on every host.
#
# Run as root. Idempotent - safe to run again. Exits 0 when everything it owns
# is gone, 1 when something could not be removed. If the onboarding script is
# still applied by config management, take it out of the run first, or it will
# put everything back.
#
# REVIEW BEFORE DEPLOYING. This removes Polaris's access to this host.
# ---------------------------------------------------------------------------

set -uo pipefail

POLARIS_KEYS=( __KEYS__ )
POLARIS_USER=__USERNAME__
POLARIS_SUDOERS=__SUDOERS_PATH__
POLARIS_FAILED=0

__SH_HELPERS__

__SH_STRIP_HELPER__

if [ "$(id -u)" -ne 0 ]; then
  echo "error: must run as root" >&2
  exit 1
fi

# --- 1. Remove the Polaris key(s) -------------------------------------------
# Only lines whose key matches are removed. Every other key in the file
# belongs to someone else and is kept, with the file's mode and owner.
if id -u "$POLARIS_USER" >/dev/null 2>&1; then
  POLARIS_HOME="$(polaris_home_for "$POLARIS_USER")"
  AUTH_KEYS="$POLARIS_HOME/.ssh/authorized_keys"
  if [ -n "$POLARIS_HOME" ] && [ -f "$AUTH_KEYS" ]; then
    if POLARIS_REMOVED="$(polaris_strip_keys "$AUTH_KEYS" "\${POLARIS_KEYS[@]}")"; then
      echo "Removed $POLARIS_REMOVED Polaris key line(s) from $AUTH_KEYS"
      if command -v restorecon >/dev/null 2>&1; then
        restorecon "$AUTH_KEYS" 2>/dev/null || true
      fi
    else
      echo "error: could not rewrite $AUTH_KEYS" >&2
      POLARIS_FAILED=1
    fi
  else
    echo "No authorized_keys file for $POLARIS_USER - no key to remove"
  fi
else
  echo "Account $POLARIS_USER not present - no key to remove"
fi

# --- 2. Passwordless sudo ---------------------------------------------------
# Removed only when it is the file the onboarding script wrote.
if [ -f "$POLARIS_SUDOERS" ]; then
  if head -n 1 "$POLARIS_SUDOERS" | grep -q "Managed by Polaris"; then
    if rm -f "$POLARIS_SUDOERS"; then
      echo "Removed $POLARIS_SUDOERS"
    else
      echo "error: could not remove $POLARIS_SUDOERS" >&2
      POLARIS_FAILED=1
    fi
  else
    echo "Left $POLARIS_SUDOERS alone: it does not carry the Polaris header, so this script did not write it"
  fi
else
  echo "No sudoers drop-in at $POLARIS_SUDOERS"
fi

# --- 3. Account -------------------------------------------------------------
__ACCOUNT_BLOCK__

__FIREWALL_BLOCK__

# --- 5. What was left -------------------------------------------------------
if [ -f /etc/systemd/system/polaris-agent.service ]; then
  echo "warning: the Polaris Agent is still installed on this host. This script does not remove it." >&2
fi
echo "sshd was not changed."

if [ "$POLARIS_FAILED" -ne 0 ]; then
  echo "Polaris SSH offboarding finished WITH ERRORS" >&2
  exit 1
fi
echo "Polaris SSH offboarding complete"
exit 0
`.trim();

/** accountMode="create": ours only while it still carries the onboarding comment. */
const LINUX_OFFBOARD_ACCOUNT_CREATE_SH = `
# Removed only when it is the account the onboarding script created: that
# script creates it with a fixed comment. An account with any other comment
# existed before onboarding, or has been repurposed, and is kept.
if id -u "$POLARIS_USER" >/dev/null 2>&1; then
  POLARIS_GECOS="$(getent passwd "$POLARIS_USER" | cut -d: -f5)"
  if [ "$POLARIS_GECOS" = __ACCOUNT_COMMENT__ ]; then
    if userdel --remove "$POLARIS_USER" >/dev/null 2>&1; then
      echo "Removed account $POLARIS_USER and its home directory"
    else
      echo "error: could not remove account $POLARIS_USER (is it still logged in or running a process?)" >&2
      POLARIS_FAILED=1
    fi
  else
    echo "Left account $POLARIS_USER alone: it does not carry the Polaris onboarding comment, so this script did not create it"
  fi
else
  echo "Account $POLARIS_USER not present"
fi
`.trim();

const LINUX_OFFBOARD_ACCOUNT_EXISTING_SH = `
# Onboarding used an account that already existed. It is not removed, locked
# or changed here beyond the key and the sudoers drop-in above.
echo "Left account $POLARIS_USER alone (onboarding did not create it)"
`.trim();

const LINUX_OFFBOARD_FIREWALL_SH = `
# --- 4. Firewall ------------------------------------------------------------
# Removes the allowance onboarding added for the Polaris server. Only the two
# front-ends onboarding handles are handled here.
POLARIS_SERVER=__SERVER_IP__
if command -v firewall-cmd >/dev/null 2>&1 && firewall-cmd --state >/dev/null 2>&1; then
  firewall-cmd --permanent --remove-rich-rule="rule family=ipv4 source address=$POLARIS_SERVER service name=ssh accept" >/dev/null 2>&1 || true
  firewall-cmd --reload >/dev/null 2>&1 || true
  echo "firewalld: removed the ssh allowance for $POLARIS_SERVER (if it was present)"
elif command -v ufw >/dev/null 2>&1 && ufw status 2>/dev/null | grep -q "Status: active"; then
  ufw delete allow from "$POLARIS_SERVER" to any port 22 proto tcp >/dev/null 2>&1 || true
  echo "ufw: removed the tcp/22 allowance for $POLARIS_SERVER (if it was present)"
else
  echo "firewall: neither firewalld nor ufw is active - not modified"
fi
`.trim();

const LINUX_OFFBOARD_NO_FIREWALL_SH = `
# --- 4. Firewall ------------------------------------------------------------
# No Polaris server address is configured, so onboarding never touched the
# firewall and neither does this script.
echo "firewall: not modified (no Polaris server address configured)"
`.trim();

export function buildLinuxOffboardingScript(opts: OffboardingScriptOptions): string {
  const publicKey = assertValidPublicKey(opts.publicKey);
  assertAccountMode(opts.accountMode);
  const username = assertValidLinuxUsername(opts.username);
  const serverIp = assertValidServerIp(opts.polarisServerIp);
  const keys = [publicKey, ...assertValidRetiredKeys(opts.retiredPublicKeys, publicKey)];

  const accountBlock =
    opts.accountMode === "create"
      ? LINUX_OFFBOARD_ACCOUNT_CREATE_SH.replace(/__ACCOUNT_COMMENT__/g, () => shLiteral(LINUX_ACCOUNT_COMMENT))
      : LINUX_OFFBOARD_ACCOUNT_EXISTING_SH;
  const firewallBlock = serverIp
    ? LINUX_OFFBOARD_FIREWALL_SH.replace(/__SERVER_IP__/g, () => shLiteral(serverIp))
    : LINUX_OFFBOARD_NO_FIREWALL_SH;

  return LINUX_OFFBOARDING_SH
    .replace(/__USERNAME__/g, () => shLiteral(username))
    .replace(/__SUDOERS_PATH__/g, () => shLiteral(LINUX_SUDOERS_PATH))
    .replace(/__SH_HELPERS__/g, () => POLARIS_SH_HELPERS)
    .replace(/__SH_STRIP_HELPER__/g, () => POLARIS_SH_STRIP_HELPER)
    .replace(/__ACCOUNT_BLOCK__/g, () => accountBlock)
    .replace(/__FIREWALL_BLOCK__/g, () => firewallBlock)
    .replace(
      /__ACCOUNT_SUMMARY__/g,
      () => opts.accountMode === "create"
        ? `the account '${username}' and its home directory, if the onboarding script created it`
        : `nothing for the account '${username}' - onboarding did not create it, so it is left alone`,
    )
    .replace(
      /__FIREWALL_SUMMARY__/g,
      () => serverIp ? `the firewall allowance for inbound TCP/22 from ${serverIp}` : "nothing in the firewall (onboarding did not touch it)",
    )
    .replace(/__KEYS__/g, () => keys.map(shLiteral).join(" "));
}
